# Introduction to Object-Oriented Programming (OOP)
# Object-Oriented Programming (OOP) is a programming paradigm that organizes programs using classes and objects. It helps in writing clean, reusable, and well-structured code. In OOP, data and the functions that work on that data are combined into a single unit called an object. Python supports OOP, making it easier to model real-world entities such as students, cars, bank accounts, and mobile phones.

# Procedural Programming vs Object-Oriented Programming
# Procedural Programming focuses on writing programs as a sequence of functions or procedures. Data and functions are separate, and the program executes step by step.
# Object-Oriented Programming focuses on objects that contain both data (attributes) and functions (methods). It makes code more modular, reusable, and easier to maintain, especially for large projects.

# Class
# A class is a blueprint or template used to create objects. It defines the attributes (data) and methods (functions) that an object will have. A class itself does not store actual data; it only describes the structure of an object.

# Object
# An object is an instance of a class. It is the real entity created from the class blueprint. Each object has its own attributes and can perform the actions defined by the class methods.

# Inheritance
# Inheritance is an OOP feature in which one class acquires the properties and methods of another class. The existing class is called the parent (base) class, and the new class is called the child (derived) class. It promotes code reusability and reduces duplication.

# Polymorphism
# Polymorphism means "many forms." It allows the same method or function name to behave differently depending on the object that uses it. This increases flexibility and makes programs easier to extend.

# Encapsulation
# Encapsulation is the process of combining data (attributes) and methods into a single unit called a class. It also helps protect data by restricting direct access to it, making programs more secure and organized.
